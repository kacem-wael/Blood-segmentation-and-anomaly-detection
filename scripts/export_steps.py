"""Write every pipeline step of each image to outputs/, one folder per step.

    outputs/01-original/<image_id>.png
    outputs/02-green_channel/<image_id>.png
    ...
    outputs/22-segmentation_overlay/<image_id>.png      (end of Phase 4: masks)
    outputs/23-wbc_lobe_grouping/<image_id>.png         (Phase 6: WBC, platelets)
    ...
    outputs/36-watershed_rbc/<image_id>.png             (Phase 5: RBC splitting)
    ...
    outputs/40-anomalies/<image_id>.png                 (Phases 8-9: classes, flags)

Folder NN holds the result of steps 1..NN applied in order. The step lists are
``bloodcells.segmentation.STEPS`` then ``bloodcells.pipeline.PIPELINE_STEPS``,
produced by the same code path as ``pipeline.run``. When the image is resampled
to the working RBC radius (``scale.working_r``), the morphology steps are shown
at the working resolution; the last two steps at the input resolution.
Float channels are min-max stretched for display (``visualization.to_uint8``).
outputs/README.md lists the steps with the parameters used, outputs/images.csv
the processed images, their r, counts and statistics.

The numbered folders are regenerated on every run (old ones are deleted).
By default 20 train/val images are exported; the test set only on request.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path

import numpy as np
import pandas as pd
import yaml
from joblib import Parallel, delayed

from bloodcells.config import PROJECT_ROOT, load_config
from bloodcells.datasets import rbc_radius_per_image
from bloodcells.io_utils import load_image
from bloodcells.classifier import load_model
from bloodcells.pipeline import PIPELINE_STEPS, pipeline_step_images, run
from bloodcells.segmentation import STEPS
from bloodcells.visualization import overlay, save_image, spectrum_figure

OUTPUTS = PROJECT_ROOT / "outputs"
STEP_DIR = re.compile(r"^\d{2}-")
ALL_STEPS = STEPS + PIPELINE_STEPS


def folder(i: int, name: str) -> str:
    return f"{i:02d}-{name}"


def export_one(image_id: str, path: str, cfg: dict, r_ref: float, out: Path, model) -> dict:
    img = load_image(path)
    res = run(img, cfg, model=model)
    seg = res.analysis.seg
    images = dict(seg.steps)
    if seg.scale is not None:
        images["scale_coarse_mask"] = seg.scale.mask
    images.update(pipeline_step_images(res, cfg))
    for i, (name, _) in enumerate(ALL_STEPS, start=1):
        target = out / folder(i, name) / f"{image_id}.png"
        if name == "scale_granulometry":
            if seg.scale is None:
                continue
            fig = spectrum_figure(seg.scale, r_ref, title=image_id)
            target.parent.mkdir(parents=True, exist_ok=True)
            fig.savefig(target, dpi=90)
        elif name == "segmentation_overlay":
            save_image(target, overlay(seg.steps["original"], seg.cell_mask, seg.purple_mask))
        elif name in images:
            save_image(target, images[name])
    s = res.summary()
    return {
        "image_id": image_id,
        "r": round(res.r, 2),
        "r_ok": bool(s["r_estimated"]),
        "r_box": r_ref,
        "resampling": round(res.factor, 3),
        "RBC": s["n_RBC"],
        "RBC_with_clumps": s["n_RBC_with_clumps"],
        "WBC": s["n_WBC"],
        "Platelet": s["n_Platelet"],
        "rbc_area_cv": round(s["rbc_area_cv"], 3) if np.isfinite(s["rbc_area_cv"]) else "",
        "wbc_nc": round(s["wbc_nc_ratio_mean"], 2) if np.isfinite(s["wbc_nc_ratio_mean"]) else "",
        "flagged": s["rbc_flagged"],
    }


def write_readme(out: Path, cfg: dict, table: pd.DataFrame) -> None:
    params = {k: cfg[k] for k in ("scale", "preprocessing", "segmentation", "wbc", "platelets", "separation")}
    lines = [
        "# Pipeline outputs",
        "",
        "Generated by `scripts/export_steps.py` (`make outputs`); do not edit by hand.",
        "Folder `NN-name` holds the result of steps 1..NN applied in order to each image.",
        "Masks are white = foreground; float channels are stretched to 0-255 for display.",
        "",
        "| # | folder | step |",
        "|---|--------|------|",
    ]
    lines += [f"| {i} | `{folder(i, n)}` | {d} |" for i, (n, d) in enumerate(ALL_STEPS, start=1)]
    lines += [
        "",
        "## Parameters (`config.yaml`)",
        "",
        "```yaml",
        yaml.safe_dump(params, sort_keys=False).strip(),
        "```",
    ]
    lines += ["", "## Images", "", "| " + " | ".join(table.columns) + " |", "|" + "---|" * len(table.columns)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in table.itertuples(index=False)]
    (out / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--config", default=None)
    parser.add_argument("--ids", nargs="*", help="image ids (default: a random train/val sample)")
    parser.add_argument("--n", type=int, default=20, help="sample size when --ids is not given")
    parser.add_argument("--split", choices=["train", "val", "trainval", "test"], default="trainval")
    parser.add_argument("--jobs", type=int, default=-1)
    args = parser.parse_args()
    cfg = load_config(args.config)
    paths = cfg["paths"]
    model = load_model(PROJECT_ROOT / cfg["classifier"]["model_file"])

    images = pd.read_csv(paths["index"] / "bccd_images.csv").set_index("image_id")
    splits = json.loads(paths["splits"].read_text(encoding="utf-8"))
    r_ref = rbc_radius_per_image(pd.read_csv(paths["index"] / "bccd_boxes.csv"))
    if args.ids:
        ids = args.ids
    else:
        pool = splits["train"] + splits["val"] if args.split == "trainval" else splits[args.split]
        if args.split == "test":
            print("Warning: exporting test images (look, do not tune on them).")
        rng = np.random.default_rng(cfg["seed"])
        ids = sorted(rng.choice(pool, min(args.n, len(pool)), replace=False))
    unknown = [i for i in ids if i not in images.index]
    if unknown:
        raise SystemExit(f"Unknown image ids: {unknown}")

    OUTPUTS.mkdir(exist_ok=True)
    for old in OUTPUTS.iterdir():
        if old.is_dir() and STEP_DIR.match(old.name):
            shutil.rmtree(old)
    print(f"Exporting {len(ALL_STEPS)} steps for {len(ids)} images to {OUTPUTS} ...")
    rows = Parallel(n_jobs=args.jobs)(
        delayed(export_one)(i, images.loc[i, "image_path"], cfg, float(r_ref.get(i, np.nan)), OUTPUTS, model)
        for i in ids
    )
    table = pd.DataFrame(rows)
    table.to_csv(OUTPUTS / "images.csv", index=False)
    write_readme(OUTPUTS, cfg, table)
    for i, (name, _) in enumerate(ALL_STEPS, start=1):
        print(f"  {folder(i, name)}")
    print(table.to_string(index=False))


if __name__ == "__main__":
    main()
